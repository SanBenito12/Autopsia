export type Key = keyof typeof es;
const dict = { es, en };

export function makeT(lang: Lang) {
  return (key: Key, ...params: (string | number)[]) =>
    dict[lang][key].replace(/\{(\d)\}/g, (_m, i) => String(params[Number(i)] ?? ''));
}
export type T = ReturnType<typeof makeT>;


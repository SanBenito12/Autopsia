export type MessageParams = Record<string, string | number>;
export interface DiagnosticMessage { code: MessageKey; params: MessageParams }
export interface Diagnostic { message: DiagnosticMessage; detail?: DiagnosticMessage }
let locale: Locale = 'en';
export function setLocale(value: Locale): void { locale = value; }
export function getLocale(): Locale { return locale; }
export function format(key: MessageKey, params: MessageParams = {}, language: Locale = locale): string {
  return (language === 'es' ? es : en)[key].replace(/\{(p\d+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match);
}
export const t = format;
/** Legacy reports intentionally retain their stored text when metadata is absent. */
export function present<T extends { message: string; detail?: string; diagnostic?: Diagnostic }>(value: T, language: Locale = locale): T {
  const render = (part: DiagnosticMessage | undefined, fallback: string | undefined): string | undefined => {
    if (!part || !Object.prototype.hasOwnProperty.call(es, part.code) || !part.params || typeof part.params !== 'object') return fallback;
    return format(part.code, part.params, language);
  };
  return { ...value, message: render(value.diagnostic?.message, value.message)!,
    ...(value.detail !== undefined ? { detail: render(value.diagnostic?.detail, value.detail) } : {}) };
}
